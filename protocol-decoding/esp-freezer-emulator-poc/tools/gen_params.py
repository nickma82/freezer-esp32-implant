#!/usr/bin/env python3
"""Build the emulator's parameter table from the captured freezer replies.

Every read request (`02 FF 02 03 01 ...` from the box, `01 FF 01 03 01 ...` from node 01) is paired with the freezer's
next reply to that node (`82 82 7F 13 01 ...` / `81 81 7F 13 01 ...`); record i of the reply answers record i of the
request. The key is (grp, id, requested flag): the freezer answers `0C/01 20` and `0C/01 21` differently.
Captures are read in priority order (normal state first); the last value seen in the first capture that has a key wins.

usage: gen_params.py <csv dir> <out header>
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'src'))
from frames import messages  # noqa: E402
from protocol import WIDTH, decode  # noqa: E402

# Normal state first (door closed, no alarm, SuperFrost/party off); event captures only fill gaps.
PRIORITY = [
    'freezer_bootup_hex.csv', 'setpoint_-18_to_-17_hex.csv', 'setpoint_-17_to_-16_hex.csv',
    'superfrost_disable_hex.csv', 'partymode_disable_hex.csv', 'bottletimer_disable_hex.csv',
    'door_short_closed_hex.csv', 'door_alarm_off_hex.csv', 'superfrost_enable_hex.csv',
    'partymode_enable_hex.csv', 'bottletimer_enable_hex.csv', 'door_short_open_hex.csv',
    'door_alarm_on_hex.csv', 'door_open_alarm_hex.csv', 'door_open_close_nop30_hex.csv', 'ch0_hex.csv',
]


def pairs(path):
    """(request recs, reply recs) for every answered read in one capture."""
    pending = {}  # node -> request recs
    for _, frame in messages(path):
        try:
            m = decode(frame)
        except ValueError:
            continue
        if m.kind not in ('list', 'values') or not m.crc_ok:
            continue
        if m.kind == 'list' and m.marker == 0xFF and m.tag == (0x03, 0x01):
            pending[m.second] = m.recs
        elif m.kind == 'values' and m.second == 0x7F and m.tag == (0x13, 0x01):
            node = m.marker & 0x7F
            req = pending.pop(node, None)
            if req is not None and len(req) == len(m.recs):
                yield req, m.recs


def collect(csv_dir):
    table = {}
    for name in PRIORITY:
        path = os.path.join(csv_dir, name)
        if not os.path.exists(path):
            continue
        local = {}
        for req, rep in pairs(path):
            for q, r in zip(req, rep):
                if (q.grp, q.id) != (r.grp, r.id):
                    continue
                local[(q.grp, q.id, q.flag)] = (r.flag, r.value, name)
        for k, v in local.items():
            table.setdefault(k, v)
    return table


def emit(table, out):
    rows = []
    for (g, i, qf), (rf, val, src) in sorted(table.items()):
        n = WIDTH[rf]
        v = int.from_bytes(val, 'big') if n else 0
        txt = ''.join(chr(b) if 32 <= b < 127 else '.' for b in val) if n == 4 else ''
        rows.append(f'    {{0x{g:02X}, 0x{i:02X}, 0x{qf:02X}, 0x{rf:02X}, {n}, 0x{v:0{max(2 * n, 2)}X}u}},'
                    f'  // {src.replace("_hex.csv", "")}{"  " + repr(txt) if txt.strip(".") else ""}')
    with open(out, 'w') as f:
        f.write('// GENERATED by tools/gen_params.py from ../../csv/*_hex.csv: do not edit by hand.\n')
        f.write('// Every value the captured freezer (node 7F) returned to a read request, keyed by (grp, id, requested flag).\n')
        f.write('// Reply flag 00 = "parameter not available" (the freezer said so itself).\n')
        f.write('#pragma once\n#include <stdint.h>\n\nnamespace fm {\n\n')
        f.write('struct CapturedParam { uint8_t grp, id, req_flag, flag, vlen; uint32_t value; };\n\n')
        f.write(f'constexpr CapturedParam CAPTURED[] = {{\n' + '\n'.join(rows) + '\n};\n')
        f.write(f'constexpr unsigned N_CAPTURED = {len(rows)};\n\n}}  // namespace fm\n')
    return len(rows)


def main():
    csv_dir, out = sys.argv[1], sys.argv[2]
    n = emit(collect(csv_dir), out)
    print(f'{n} parameters -> {out}')


if __name__ == '__main__':
    main()
