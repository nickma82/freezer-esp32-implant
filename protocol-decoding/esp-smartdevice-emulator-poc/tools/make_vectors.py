#!/usr/bin/env python3
"""Generate test/test_core/vectors.h from ../csv/*_hex.csv with the expected decode of every distinct slot.
Reuses ../src/slots.py (bursts) and ../src/protocol.py (decode, interpret), so the C++ core is checked against
the reference implementation. Messages with group 3C (identification) or 48 (network) records are left out, so no
serial numbers, SSID, IP or MAC end up in the repository. Usage: python3 tools/make_vectors.py"""
import glob, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))          # protocol-decoding/
sys.path.insert(0, os.path.join(ROOT, 'src'))
import protocol as P
from slots import bursts

SKIP_GROUPS = {0x3C, 0x48}
KIND = {'bare': 'Empty', 'ack': 'Ack', 'list': 'List', 'values': 'Values', 'unknown': 'Unknown'}

def expected_items(m):
    """interpret() plus door_push (14/04), in record order, rendered as name=text like the C++ Item."""
    py = {n: v for n, v in P.interpret(m)}
    out = []
    if 'event' in py:
        return [f'event={py["event"]}']
    seen = set()
    for r in m.recs:
        k = (r.grp, r.id)
        if k in seen: continue
        seen.add(k)
        if k == (0x14, 0x04) and r.value:
            out.append(f'door_push={int(bool(r.value[0]))}')
        elif k in P.KNOWN and P.KNOWN[k] in py:
            v = py[P.KNOWN[k]]
            out.append(f'{P.KNOWN[k]}={int(v) if isinstance(v, bool) else v}')
    return out

def main():
    seen, rows, skipped, errors = set(), [], 0, 0
    for path in sorted(glob.glob(os.path.join(ROOT, 'csv', '*_hex.csv'))):
        for _, b, _ in bursts(path):
            if not b or bytes(b) in seen: continue
            seen.add(bytes(b))
            try:
                m = P.decode(bytes(b))
            except ValueError:
                errors += 1; continue                   # e.g. a message cut off by the end of a capture
            if any(r.grp in SKIP_GROUPS for r in m.recs): skipped += 1; continue
            rows.append((bytes(b), m))
    out = ['// Generated by tools/make_vectors.py from ../csv/*_hex.csv. Do not edit.',
           '// Groups 3C and 48 are left out. Fields: bytes, len, kind, crc_ok, nrecs, dst, src, svc, flag, interp.',
           '#pragma once', '#include <stdint.h>', '#include "freezer_bus.h"',
           'struct Vector { const uint8_t* bytes; uint16_t len; lb::Kind kind; bool crc_ok; uint8_t nrecs;',
           '                uint8_t dst, src, svc, flag; const char* interp; };']
    for i, (b, _) in enumerate(rows):
        out.append(f'static const uint8_t V{i}[] = {{{",".join(f"0x{x:02X}" for x in b)}}};')
    out.append('static const Vector VECTORS[] = {')
    for i, (b, m) in enumerate(rows):
        d = (m.marker or 0, m.second or 0, m.tag[0] if m.tag else 0, m.tag[1] if m.tag else 0)
        interp = ';'.join(expected_items(m))
        out.append(f'  {{V{i}, {len(b)}, lb::Kind::{KIND[m.kind]}, {str(bool(m.crc_ok)).lower()}, {len(m.recs)}, '
                   f'0x{d[0]:02X}, 0x{d[1]:02X}, 0x{d[2]:02X}, 0x{d[3]:02X}, "{interp}"}},')
    out.append('};')
    out.append(f'static const unsigned VECTOR_COUNT = {len(rows)};')
    dest = os.path.join(os.path.dirname(HERE), 'test', 'test_core', 'vectors.h')
    open(dest, 'w').write('\n'.join(out) + '\n')
    print(f'{len(rows)} vectors -> {dest} (skipped {skipped} with groups 3C/48, {errors} undecodable)')

if __name__ == '__main__':
    main()
